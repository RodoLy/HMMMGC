"""The DOLRECOMP_SYMBOL_* header for mods. No game data needed.

El header DOLRECOMP_SYMBOL_* para mods. Sin datos del juego."""

import subprocess
import sys
from pathlib import Path

import pytest

TOOLS_DIRECTORY = Path(__file__).resolve().parent.parent / "tools"
sys.path.insert(0, str(TOOLS_DIRECTORY))

from export_mod_symbols import dolrecomp_identifier, mod_symbol_header  # noqa: E402
from project import SYMBOLS_PATH  # noqa: E402
from symbols import Symbol, SymbolTable  # noqa: E402


@pytest.mark.parametrize(
    ("name", "identifier"),
    [
        ("OSInit", "OSInit"),
        ("__start", "_start"),  # runs of '_' collapse, as in DolRecomp
        ("__init_registers", "_init_registers"),
        ("3dMain", "_3dMain"),  # a C identifier cannot start with a digit
        ("operator new[]", "operator_new"),  # trailing '_' are dropped
        ("café", "caf"),  # non-ASCII bytes are not identifier characters
        ("___", "_"),
        ("a" * 200, "a" * 111),  # DolRecomp's 112-byte buffer
    ],
)
def test_identifiers_follow_dolrecomp_rules(name, identifier):
    assert dolrecomp_identifier(name) == identifier


def test_an_empty_name_is_an_error():
    with pytest.raises(ValueError):
        dolrecomp_identifier("")


def test_header_has_dolrecomp_format_and_only_functions():
    table = SymbolTable(
        [
            Symbol("OSInit", ".text", 0x8016EF2C, "function", 0x4E0),
            Symbol("jumptable_80202AB4", ".data", 0x80202AB4, "object", 0x30, scope="local"),
            Symbol("fn_80003100", ".init", 0x80003100, "function", 0x40),
        ]
    )
    assert mod_symbol_header(table).splitlines() == [
        "/* Functions of G4AEE9 for mods. Generated by tools/export_mod_symbols.py",
        " * from config/G4AEE9/symbols.txt; do not edit by hand. */",
        "#ifndef DOLRECOMP_GENERATED_SYMBOLS_H",
        "#define DOLRECOMP_GENERATED_SYMBOLS_H",
        "",
        "#define DOLRECOMP_SYMBOL_COUNT 2u",
        "#define DOLRECOMP_SYMBOL_fn_80003100 0x80003100u",
        "#define DOLRECOMP_SYMBOL_SIZE_fn_80003100 0x00000040u",
        "#define DOLRECOMP_SYMBOL_OSInit 0x8016EF2Cu",
        "#define DOLRECOMP_SYMBOL_SIZE_OSInit 0x000004E0u",
        "",
        "#endif",
    ]


def test_colliding_identifiers_get_the_address_then_a_counter():
    table = SymbolTable(
        [
            Symbol("_foo", ".text", 0x80001000, "function", 0x10),
            Symbol("_foo_80002000", ".text", 0x80001800, "function", 0x10),
            Symbol("__foo", ".text", 0x80002000, "function", 0x10),  # also "_foo"
        ]
    )
    header_lines = mod_symbol_header(table).splitlines()
    address_lines = [line for line in header_lines if line.startswith("#define DOLRECOMP_SYMBOL__foo")]
    assert address_lines == [
        "#define DOLRECOMP_SYMBOL__foo 0x80001000u",
        "#define DOLRECOMP_SYMBOL__foo_80002000 0x80001800u",
        "#define DOLRECOMP_SYMBOL__foo_80002000_1 0x80002000u",
    ]


def test_every_function_of_the_real_map_gets_a_unique_macro():
    table = SymbolTable.read(SYMBOLS_PATH)
    functions = [symbol for symbol in table if symbol.kind == "function"]
    address_lines = [
        line
        for line in mod_symbol_header(table).splitlines()
        if line.startswith("#define DOLRECOMP_SYMBOL_")
        and not line.startswith(("#define DOLRECOMP_SYMBOL_SIZE_", "#define DOLRECOMP_SYMBOL_COUNT"))
    ]
    macro_names = [line.split()[1] for line in address_lines]
    assert len(macro_names) == len(functions)
    assert len(set(macro_names)) == len(macro_names)
    assert "#define DOLRECOMP_SYMBOL_OSInit 0x8016EF2Cu" in address_lines


def test_the_command_writes_utf8_with_lf_endings(tmp_path):
    symbols_path = tmp_path / "symbols.txt"
    SymbolTable([Symbol("OSInit", ".text", 0x8016EF2C, "function", 0x4E0)]).write(symbols_path)
    header_path = tmp_path / "out" / "G4AEE9_symbols.h"
    subprocess.run(
        [
            sys.executable,
            str(TOOLS_DIRECTORY / "export_mod_symbols.py"),
            "--symbols",
            str(symbols_path),
            "--out",
            str(header_path),
        ],
        check=True,
        capture_output=True,
    )
    written = header_path.read_bytes()
    assert b"\r" not in written
    assert written.decode("utf-8") == mod_symbol_header(SymbolTable.read(symbols_path))
