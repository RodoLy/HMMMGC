#!/usr/bin/env python3
"""Write what WiiCompiled's translator needs to translate main.dol: its project file
and the function map.

Escribe lo que necesita el traductor de WiiCompiled para traducir main.dol: su archivo
de proyecto y el mapa de funciones.

The translator (github.com/patchzyy/wiicompiled, translator/) reads a YAML project
that says where the DOL is, where the game's memory and small-data areas are, where to
write the C++ and which folder holds the runtime's native replacements (it leaves
those functions out of the translation). The function map is one "address name" line
per function of symbols.txt; the translator takes each address as a function start.

El traductor lee un proyecto YAML que dice dónde está el DOL, dónde están la memoria
del juego y sus áreas de datos pequeños, dónde escribir el C++ y qué carpeta tiene los
reemplazos nativos del runtime (deja esas funciones fuera de la traducción). El mapa de
funciones tiene una línea "dirección nombre" por función de symbols.txt.

Prints the DOL's entry point, which is where the translation starts.

Usage / Uso:
    python3 tools/write_translator_project.py --out build/native/translation
    dotnet Translator.Cli.dll translate-recursive <entry point> \
        --project build/native/translation/project.yml ...
"""

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from dol import Dol  # noqa: E402
from function_finder import (  # noqa: E402
    SMALL_DATA_2_BASE_REGISTER,
    SMALL_DATA_BASE_REGISTER,
    find_small_data_bases,
)
from project import BUILD_DIRECTORY, MAIN_DOL_PATH, REPOSITORY_ROOT, SYMBOLS_PATH  # noqa: E402
from symbols import SymbolTable  # noqa: E402
from textfiles import write_text  # noqa: E402

DEFAULT_OUTPUT_DIRECTORY = BUILD_DIRECTORY / "native" / "translation"
DEFAULT_NATIVES_DIRECTORY = REPOSITORY_ROOT / "runtime" / "src"
FUNCTION_MAP_NAME = "functions.txt"
PROJECT_NAME = "project.yml"
TRANSLATED_GAME_FOLDER = "game"

# Main memory as the CPU sees it (MEM1, 24 MiB at 0x80000000).
MEMORY_BASE = 0x80000000
MEMORY_SIZE = 0x01800000


def translator_map_lines(table: SymbolTable) -> list[str]:
    """One "address name" line per function, in address order."""
    return [f"{symbol.address:08X} {symbol.name}" for symbol in table if symbol.kind == "function"]


def yaml_path(path: Path) -> str:
    """A path for the project file, quoted: on a player's computer it holds their folders, whose
    names may have characters that YAML would read otherwise ("#", ": "). A JSON string is a YAML
    one."""
    return json.dumps(path.resolve().as_posix(), ensure_ascii=False)


def project_text(
    dol_path: Path, natives_directory: Path, small_data_base: int, small_data_2_base: int
) -> str:
    """The translator's project file. Its relative paths are relative to its own folder."""
    return f"""# Written by tools/write_translator_project.py; regenerated by every build.
schema_version: 1
workspace_root: .

project:
  id: harvest-moon-magical-melody
  display_name: Harvest Moon Magical Melody

memory:
  base: 0x{MEMORY_BASE:08X}
  size: 0x{MEMORY_SIZE:08X}
  # What __init_registers puts in r13 and r2.
  sda_base: 0x{small_data_base:08X}
  sda2_base: 0x{small_data_2_base:08X}

inputs:
  dol:
    path: {yaml_path(dol_path)}

translation:
  # The OS reads and writes special registers the translator does not know by number
  # (BATs, L2CR, performance monitors); it emits PPC_ReadSpr/PPC_WriteSpr for them,
  # which the runtime provides.
  allow_unsupported_instructions: true
  function_map:
    path: {FUNCTION_MAP_NAME}

runtime:
  native_registration_root: {yaml_path(natives_directory)}
  native_abi_directories: []

output:
  root: {TRANSLATED_GAME_FOLDER}
  functions: functions
  runtime_config: RuntimeConfig.h
  data_initializer: data_sections_init.cpp
  base_manifest: base/base_manifest.json
"""


def main() -> int:
    parser = argparse.ArgumentParser(description="Write the translator's project file and function map.")
    parser.add_argument("--dol", type=Path, default=MAIN_DOL_PATH, help=f"default: {MAIN_DOL_PATH}")
    parser.add_argument("--symbols", type=Path, default=SYMBOLS_PATH, help=f"default: {SYMBOLS_PATH}")
    parser.add_argument(
        "--natives",
        type=Path,
        default=DEFAULT_NATIVES_DIRECTORY,
        help=f"the runtime's sources (default: {DEFAULT_NATIVES_DIRECTORY})",
    )
    parser.add_argument(
        "--out", type=Path, default=DEFAULT_OUTPUT_DIRECTORY, help=f"default: {DEFAULT_OUTPUT_DIRECTORY}"
    )
    arguments = parser.parse_args()

    dol = Dol(arguments.dol)
    bases = find_small_data_bases(dol)
    if SMALL_DATA_BASE_REGISTER not in bases or SMALL_DATA_2_BASE_REGISTER not in bases:
        parser.error(f"could not find where __init_registers sets r2 and r13 in {arguments.dol}")
    table = SymbolTable.read(arguments.symbols)
    if not len(table):
        parser.error(f"no symbols found in {arguments.symbols}")

    lines = translator_map_lines(table)
    project = project_text(
        arguments.dol, arguments.natives, bases[SMALL_DATA_BASE_REGISTER], bases[SMALL_DATA_2_BASE_REGISTER]
    )
    arguments.out.mkdir(parents=True, exist_ok=True)
    write_text(arguments.out / FUNCTION_MAP_NAME, "\n".join(lines) + "\n")
    write_text(arguments.out / PROJECT_NAME, project)
    summary = f"wrote {arguments.out}: {PROJECT_NAME}, {FUNCTION_MAP_NAME} ({len(lines)} functions)"
    print(summary, file=sys.stderr)
    print(f"0x{dol.entry:08X}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
