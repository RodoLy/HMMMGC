#!/usr/bin/env python3
"""Write the C header that lets mods refer to the game's functions by name.

Escribe el header de C con el que los mods se refieren a las funciones del
juego por su nombre.

A ModernGekko mod replaces or hooks a function by its address, for example
``RECOMP_PATCH(DOLRECOMP_SYMBOL_OSResetSystem, my_replacement)``. DolRecomp
writes those DOLRECOMP_SYMBOL_* macros into ``<output>_symbols.h`` when it is
given a symbol map (``--map``). With the C backend that header is the only
thing the map changes, so it is generated here instead, straight from
symbols.txt: renaming a function then takes a second instead of rebuilding
the game module, and moderngekko-port (which does not pass ``--map``) needs
no changes. The output follows DolRecomp's format exactly (src/backend/
symbols.c and symbol_name_to_identifier() in src/analysis/symbol_map.c), so a
mod compiles the same against either header.

Un mod de ModernGekko reemplaza o intercepta una función por su dirección,
por ejemplo ``RECOMP_PATCH(DOLRECOMP_SYMBOL_OSResetSystem, mi_reemplazo)``.
DolRecomp escribe esas macros en ``<salida>_symbols.h`` cuando recibe un
mapa de símbolos (``--map``). Con el backend de C ese header es lo único que
cambia el mapa, así que aquí se genera directo de symbols.txt: renombrar una
función tarda un segundo en vez de recompilar el módulo del juego, y no hay
que modificar moderngekko-port (que no pasa ``--map``). El formato es
idéntico al de DolRecomp, así que un mod compila igual con cualquiera de los
dos headers.

Usage / Uso:
    python3 tools/export_mod_symbols.py                   # -> build/G4AEE9_symbols.h
    python3 tools/export_mod_symbols.py --out path/to/G4AEE9_symbols.h
"""

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from project import BUILD_DIRECTORY, GAME_ID, SYMBOLS_PATH  # noqa: E402
from symbols import SymbolTable  # noqa: E402

DEFAULT_HEADER_PATH = BUILD_DIRECTORY / f"{GAME_ID}_symbols.h"

# DolRecomp's own include guard: a mod that ends up including both headers
# gets the first one only, and both hold the same definitions.
HEADER_GUARD = "DOLRECOMP_GENERATED_SYMBOLS_H"
ADDRESS_MACRO_PREFIX = "DOLRECOMP_SYMBOL_"
SIZE_MACRO_PREFIX = "DOLRECOMP_SYMBOL_SIZE_"

# DolRecomp builds each identifier in a 112-byte buffer (111 characters + NUL).
MAX_IDENTIFIER_LENGTH = 111


def dolrecomp_identifier(name: str) -> str:
    """Return the C identifier DolRecomp derives from a symbol name.

    Same rules as symbol_name_to_identifier(): every byte that is not an
    ASCII letter, digit or underscore becomes '_', a leading digit gets a '_'
    in front, runs of '_' collapse into one (so ``__start`` becomes
    ``_start``), trailing '_' are dropped and the result is cut at 111
    characters.
    """
    characters: list[str] = []
    previous_was_underscore = False
    for byte in name.encode("utf-8"):
        character = chr(byte)
        is_identifier_character = byte < 0x80 and (character.isalnum() or character == "_")
        emitted = character if is_identifier_character else "_"
        if not characters and emitted.isdigit():
            characters.append("_")
        if emitted == "_" and previous_was_underscore:
            continue
        if len(characters) >= MAX_IDENTIFIER_LENGTH:
            break
        characters.append(emitted)
        previous_was_underscore = emitted == "_"
    while len(characters) > 1 and characters[-1] == "_":
        characters.pop()
    if not characters:
        raise ValueError(f"symbol name {name!r} gives an empty C identifier")
    return "".join(characters)


def mod_symbol_header(table: SymbolTable) -> str:
    """Build the header text for every function in the table, in address order."""
    functions = sorted(
        (symbol for symbol in table if symbol.kind == "function"),
        key=lambda symbol: (symbol.address, symbol.name),
    )
    used_identifiers: set[str] = set()
    definitions: list[str] = []
    for function in functions:
        base = dolrecomp_identifier(function.name)
        identifier = base
        # Like DolRecomp, a second symbol with the same identifier gets its
        # address appended, then a counter if even that is taken.
        collision_number = 0
        while identifier in used_identifiers:
            identifier = f"{base}_{function.address:08X}"
            if collision_number:
                identifier += f"_{collision_number}"
            collision_number += 1
        used_identifiers.add(identifier)
        definitions.append(f"#define {ADDRESS_MACRO_PREFIX}{identifier} 0x{function.address:08X}u")
        definitions.append(f"#define {SIZE_MACRO_PREFIX}{identifier} 0x{function.size:08X}u")

    return "\n".join(
        [
            f"/* Functions of {GAME_ID} for mods. Generated by tools/export_mod_symbols.py",
            " * from config/G4AEE9/symbols.txt; do not edit by hand. */",
            f"#ifndef {HEADER_GUARD}",
            f"#define {HEADER_GUARD}",
            "",
            f"#define DOLRECOMP_SYMBOL_COUNT {len(functions)}u",
            *definitions,
            "",
            "#endif",
            "",
        ]
    )


def main() -> int:
    parser = argparse.ArgumentParser(description="Write the DOLRECOMP_SYMBOL_* header for mods.")
    parser.add_argument("--symbols", type=Path, default=SYMBOLS_PATH, help=f"default: {SYMBOLS_PATH}")
    parser.add_argument(
        "--out", type=Path, default=DEFAULT_HEADER_PATH, help=f"default: {DEFAULT_HEADER_PATH}"
    )
    arguments = parser.parse_args()

    table = SymbolTable.read(arguments.symbols)
    for line_number, line in table.unparsed_lines:
        print(f"warning: {arguments.symbols}:{line_number} could not be parsed: {line}")
    function_count = sum(1 for symbol in table if symbol.kind == "function")
    if not function_count:
        parser.error(f"no functions found in {arguments.symbols}")

    arguments.out.parent.mkdir(parents=True, exist_ok=True)
    # Same bytes on every OS: Windows would otherwise write CRLF in its ANSI code page.
    arguments.out.write_text(mod_symbol_header(table), encoding="utf-8", newline="\n")
    print(f"wrote {arguments.out}: {function_count} functions")
    return 0


if __name__ == "__main__":
    sys.exit(main())
