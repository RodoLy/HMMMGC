// The native runtime of Harvest Moon: Magical Melody, in progress: runs the game's
// translated code from its entry point, without Dolphin; it draws, reads the controllers
// and keeps the memory card through aurora, and plays the sound through SDL. The log says
// what the game does (docs/NATIVE_RUNTIME.md).
//
// El runtime nativo de Harvest Moon: Magical Melody, en progreso: corre el código
// traducido del juego desde su punto de entrada, sin Dolphin; dibuja, lee los controles y
// guarda en la memory card con aurora, y toca el sonido con SDL. El registro dice lo que
// hace el juego.
//
// Usage: hmmm-native --disc <extracted disc> [--symbols <symbols.txt>] [--watchdog <s>]
//                    [--user-folder <folder>]

#include "console_boot.h"
#include "extracted_disc.h"
#include "fault_handler.h"
#include "game_clock.h"
#include "guest_memory.h"
#include "guest_symbols.h"
#include "hardware/hardware_registers.h"
#include "mods/native_mods.h"
#include "player_folder.h"
#include "runtime_log.h"

#include "guest_abi/guest_abi.h"

#include <cstdlib>
#include <cstring>
#include <exception>
#include <optional>
#include <string>
#include <vector>

// Generated by the translator (`generate-data-init`): copies the sections of main.dol
// into guest memory.
extern "C" void InitializeDataSections();

namespace {

struct Options {
    std::string disc_root;
    std::string symbols_path;
    unsigned watchdog_seconds = 10;
    std::string user_folder;  // empty: the default player folder (player_folder.h)
    // The mods to turn on, of those compiled in (--mods a,b or --mods none); all when not given.
    std::optional<std::vector<std::string>> mods;
    unsigned game_speed_percent = 100;  // how fast the whole game runs (game_clock.h)
};

constexpr const char* USAGE =
    "usage: hmmm-native --disc <extracted disc> [--symbols <file>] [--watchdog <s>] [--user-folder <folder>]\n"
    "                   [--mods <id,id,...> | --mods none] [--game-speed <100-400>]";

// "a,b" -> {"a", "b"}; "none" -> {}.
std::vector<std::string> split_mod_list(const std::string& value) {
    std::vector<std::string> mods;
    if (value == "none") {
        return mods;
    }
    size_t start = 0;
    while (start <= value.size()) {
        const size_t comma = value.find(',', start);
        const size_t end = comma == std::string::npos ? value.size() : comma;
        if (end > start) {
            mods.push_back(value.substr(start, end - start));
        }
        start = end + 1;
    }
    return mods;
}

Options parse_options(int argc, char** argv) {
    Options options;
    for (int i = 1; i + 1 < argc; i += 2) {
        const std::string name = argv[i];
        const std::string value = argv[i + 1];
        if (name == "--disc") {
            options.disc_root = value;
        } else if (name == "--symbols") {
            options.symbols_path = value;
        } else if (name == "--watchdog") {
            options.watchdog_seconds = static_cast<unsigned>(std::stoul(value));
        } else if (name == "--user-folder") {
            options.user_folder = value;
        } else if (name == "--mods") {
            options.mods = split_mod_list(value);
        } else if (name == "--game-speed") {
            options.game_speed_percent = static_cast<unsigned>(std::stoul(value));
        } else {
            throw std::runtime_error("unknown option " + name);
        }
    }
    if (options.disc_root.empty()) {
        throw std::runtime_error(USAGE);
    }
    return options;
}

}  // namespace

int main(int argc, char** argv) {
    try {
        const Options options = parse_options(argc, argv);
        if (!options.symbols_path.empty() && !guest_symbols::load(options.symbols_path)) {
            runtime_log::warning("boot", "could not read the symbols in %s", options.symbols_path.c_str());
        }
        const ExtractedDisc disc(options.disc_root);
        player_folder::choose(options.user_folder);

        game_clock::set_chosen_speed_percent(options.game_speed_percent);
        guest_memory::initialize();
        fault_handler::install(options.watchdog_seconds);
        hardware_registers::initialize(disc);
        TranslatedFunctionRegistry::Finalize();

        InitializeDataSections();
        console_boot::prepare_memory(disc);
        native_mods::load(options.mods ? &*options.mods : nullptr);

        CpuContext& cpu = GetPersistentCpuContext();
        console_boot::prepare_cpu(cpu);
        const uint32_t entry_point = console_boot::entry_point(disc);
        runtime_log::info("boot", "starting the game at %s", guest_symbols::describe(entry_point).c_str());

        CpuContextScope scope(&cpu);
        InvokeIndirectCpu(entry_point, &cpu);
        runtime_log::info("boot", "the game's entry point returned");
        return EXIT_SUCCESS;
    } catch (const std::exception& error) {
        runtime_log::error("boot", "%s", error.what());
        return EXIT_FAILURE;
    }
}
